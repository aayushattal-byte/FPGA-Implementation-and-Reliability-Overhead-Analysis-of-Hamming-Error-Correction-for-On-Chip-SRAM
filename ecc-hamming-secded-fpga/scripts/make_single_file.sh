#!/usr/bin/env bash
# Concatenate the six RTL modules into ONE file for the Vivado project
# (vivado/ecc_sram_top.v). The split files under rtl/sram64/ stay the source of truth.
set -euo pipefail
cd "$(dirname "$0")/.."
out=vivado/ecc_sram_top.v
{
  echo "// GENERATED by scripts/make_single_file.sh from rtl/sram64/*.v -- do not edit by hand."
  echo "// Add THIS one file to Vivado as a design source; set top_ecc_demo as the top module."
  for f in hamming_encoder hamming_decoder ecc_sram_wrapper fault_injector stats_logger top_ecc_demo; do
    echo; echo "// ---------------- $f.v ----------------"; cat rtl/sram64/$f.v
  done
} > "$out"
echo "wrote $out"
